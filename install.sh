#!/bin/bash
# Указывает системе, что это скрипт на языке Bash (оболочка командной строки)

# 1. Проверка на права root (sudo)
# $EUID — это переменная, которая хранит ID текущего пользователя.
# У root ID = 0. Если ID не равен 0, значит, скрипт запущен без sudo.
if [ "$EUID" -ne 0 ]; then
  echo -e "\033[1;31m[Ошибка] Запустите скрипт с sudo:\033[0m" # Красный текст
  echo "sudo ./install.sh"
  exit 1 # Завершаем скрипт с кодом ошибки
fi

# 2. Проверка, установлен ли уже shark24
# -f проверяет, существует ли обычный файл по указанному пути.
if [ -f "/usr/local/bin/shark24" ]; then
  echo -e "\033[1;33m[Внимание] shark24 уже установлен в /usr/local/bin.\033[0m" # Желтый текст
  # read -p запрашивает ввод у пользователя и сохраняет его в переменную choice
  read -p "Хотите переустановить/обновить его? (y/n): " choice
  
  # case — это аналог switch/case из C. Он сравнивает значение choice.
  case "$choice" in
    y|Y ) echo -e "\033[1;34m[shark24] Продолжаем обновление...\033[0m" ;;
    n|N ) echo -e "\033[1;31m[shark24] Установка отменена.\033[0m"; exit 0 ;; # exit 0 — успешный выход
    * ) echo -e "\033[1;31m[Ошибка] Неверный ввод. Установка отменена.\033[0m"; exit 1 ;; # * — все остальные варианты
  esac
else
  # Если файла нет, просто начинаем установку
  echo -e "\033[1;34m[shark24] Начинаем установку...\033[0m" # Синий текст
fi

# 3. Очистка старых объектных файлов
# > /dev/null 2>&1 означает "выкинуть весь вывод (и обычный, и ошибки) в никуда".
# Это нужно, чтобы make clean не засорял экран пользователя.
make clean > /dev/null 2>&1

# 4. Сборка проекта
echo -e "\033[1;34m[shark24] Сборка проекта...\033[0m"
make

# 5. Проверка результата сборки
# $? — это код возврата последней выполненной команды (make).
# Если make завершился с ошибкой, $? не будет равен 0.
if [ $? -ne 0 ]; then
  echo -e "\033[1;31m[Ошибка] Сборка не удалась! Установка прервана.\033[0m"
  exit 1
fi

# 6. Копирование бинарника
echo -e "\033[1;34m[shark24] Копирование в /usr/local/bin...\033[0m"
cp shark24 /usr/local/bin/shark24

# 7. Выдача прав на выполнение
# Без этого файл будет просто текстом, а не программой, которую можно запустить.
chmod +x /usr/local/bin/shark24

# 8. Финальная уборка
# Удаляем .o файлы и бинарник из папки проекта, чтобы не засорять репозиторий.
make clean > /dev/null 2>&1

# 9. Сообщение об успехе
echo -e "\033[1;32m[shark24] Установка завершена! Shark24 готов к охоте 🦈\033[0m" # Зеленый текст